// ---------- 定時の時報（毎日） ----------
// label（省略可）: アカウントページのON/OFF設定に表示する名前。省略すると「0:00 の時報」のように自動で付きます。
// ON/OFFは id ごとに保存されます。id を変えると、その時報のON/OFF設定は初期状態（ON）に戻ります。
globalThis.JIHOU_SCHEDULE = [
  { id: "0000", hour: 0, minute: 0, file: "media/jihou0.mp4" },
  { id: "0200", hour: 2, minute: 0, file: "media/jihou2.mp4" },
];

// ---------- イベント時報（手動で追加） ----------
// 定時の時報と同じ「分」に重なった場合は、イベント時報が優先され、定時の時報は出ません。
//
//   id             : 重複しない名前（必須）
//   enabled        : false にすると無効（省略時は有効）
//   at             : 開始日時 "YYYY-MM-DD HH:MM"（必須）
//   file           : 時報動画（544x56推奨。media/events/ に置くと整理しやすい）（必須）
//   url            : 時報をクリックしたときに開くURL（イベント時報では必須）
//   message        : 時報が終わった直後に、ニュース／お知らせ欄の最初に「一度だけ」表示する文（省略可）
//                    次の項目に切り替わる（または✕で消す）と、二度と表示されません
//   messageUrl     : message をクリックしたときに開くURL（省略時は url と同じ）
//
// イベントはいくつでも並べて予約できます（下の配列に { … }, を足すだけ）。
// ただし、近い時刻に複数入れる場合は、時報動画の長さ＋余裕（目安1分以上）あけてください。
// 再生中に次の時報の時刻が来ると、そちらの時報は出ません。
//
// 下の例は無効(enabled:false)の見本です。コピーして、日時・動画・URLを書き換えて使ってください。
// ※ 動作テスト: ニコニコ動画の視聴ページのコンソールで
//     document.dispatchEvent(new Event("jihou:event"))
//   と入力すると、このリストの「1番目」のイベントを（enabled や日時に関係なく）今すぐ試せます。
globalThis.JIHOU_EVENTS = [
  {
    id: "niconico-17th-example",
    enabled: false,
    at: "2023-12-12 00:00",
    file: "media/jihou0.mp4",
    url: "https://www.nicovideo.jp/",
    message: "【ニコニコ17周年】ありがとうございます！18年目もニコニコしましょう！",
    messageUrl: "https://www.nicovideo.jp/",
  },
];
